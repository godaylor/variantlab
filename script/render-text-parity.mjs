import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../', import.meta.url));
assert.equal(process.versions.node,'22.15.1');
const result = spawnSync('docker',['run','--rm','-e','CARGO_BUILD_JOBS=1','-v',`${root}:/workspace`,'-v',`${path.join(root,'.cargo-tools/registry')}:/usr/local/cargo/registry`,'-w','/workspace','variantlab-rust:1.91.1-wasm-pack-0.13.1-v3','cargo','run','--locked','--quiet','-p','render-plan','--example','text_parity'],{cwd:root,encoding:'utf8'});
if(result.status !== 0) throw new Error(result.stderr || 'Native fixture failed');
const fixture = JSON.parse(result.stdout);
const wasm = await import(pathToFileURL(path.join(root,'rust/wasm/pkg/variantlab_wasm_bg.js')));
const { instance } = await WebAssembly.instantiate(readFileSync(path.join(root,'rust/wasm/pkg/variantlab_wasm_bg.wasm')),{'./variantlab_wasm_bg.js':wasm});
wasm.__wbg_set_wasm(instance.exports);
if(typeof instance.exports.__wbindgen_start === 'function') instance.exports.__wbindgen_start();
const json = JSON.stringify(fixture.manifest);
assert.deepEqual(JSON.parse(wasm.renderOverlays(json)),fixture.overlays);
const pixels = wasm.renderTextOverlay(json,'headline');
assert.equal(pixels.byteLength,fixture.byte_length);
assert.equal(createHash('sha256').update(pixels).digest('hex'),fixture.pixel_sha256);
const png = new Uint8Array(fixture.logo.png);
assert.deepEqual(JSON.parse(wasm.probeLogoPng(png)),fixture.logo.probe);
const logoPixels = wasm.renderLogoOverlay(JSON.stringify(fixture.logo.manifest),'headline',png);
assert.equal(logoPixels.byteLength,fixture.logo.byte_length);
assert.equal(createHash('sha256').update(logoPixels).digest('hex'),fixture.logo.pixel_sha256);
console.log(JSON.stringify({gate:'native-wasm-logo-raster',result:'PASS',byteLength:logoPixels.byteLength,sha256:fixture.logo.pixel_sha256,corpus:'repository-generated PNG, explicit contain rectangle, transparency'}));
console.log(JSON.stringify({gate:'native-wasm-text-raster',result:'PASS',byteLength:pixels.byteLength,sha256:fixture.pixel_sha256,font:'Inter Regular 4.1',corpus:'RU/EN literal text, explicit placement, centered alignment, alpha=180'}));
